import {createClient} from "npm:@supabase/supabase-js@2";
const origin="https://rut-iq-preview.onrender.com";
const cors={"Access-Control-Allow-Origin":origin,"Access-Control-Allow-Headers":"authorization,apikey,content-type,x-client-info","Access-Control-Allow-Methods":"POST,OPTIONS","Cache-Control":"no-store"};
const reply=(status:number,data:object)=>new Response(JSON.stringify(data),{status,headers:{"Content-Type":"application/json",...cors}});
Deno.serve(async req=>{
 if(req.method==="OPTIONS")return new Response(null,{status:204,headers:cors});
 if(req.method!=="POST")return reply(405,{error:"POST only"});
 if(req.headers.get("Origin")!==origin)return reply(403,{error:"Invalid origin"});
 const secret=Deno.env.get("STRIPE_RUT_IQ_LIVE_SECRET");
 if(!secret?.startsWith("sk_live_"))return reply(503,{error:"Live billing unavailable"});
 const token=(req.headers.get("Authorization")||"").replace(/^Bearer\s+/i,"");
 const url=Deno.env.get("SUPABASE_URL"),key=Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
 if(!token||!url||!key)return reply(401,{error:"Sign in required"});
 const db=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
 const {data:{user},error}=await db.auth.getUser(token);
 if(error||!user)return reply(401,{error:"Invalid login"});
 const query="metadata['rut_user_id']:'"+user.id+"'";
 const search=await fetch("https://api.stripe.com/v1/subscriptions/search?"+new URLSearchParams({query,limit:"100"}),{headers:{Authorization:"Bearer "+secret}});
 if(!search.ok)return reply(503,{error:"Billing lookup unavailable"});
 const results=await search.json();
 const allowed=new Set(["price_1UQdln2MI0v3aLys9deDSpnr","price_1UQdlq2MI0v3aLys8zznDb9u"]);
 const subscriptions=(results.data||[]).filter((s:any)=>s.livemode&&s.metadata?.app==="rut_iq"&&s.metadata?.rut_user_id===user.id&&s.items?.data?.length===1&&allowed.has(s.items.data[0].price?.id));
 if(!subscriptions.length)return reply(404,{error:"No Rut IQ subscription"});
 const customers=[...new Set(subscriptions.map((s:any)=>typeof s.customer==="string"?s.customer:s.customer?.id))];
 if(customers.length!==1||!customers[0])return reply(409,{error:"Billing account needs support"});
 const params=new URLSearchParams({customer:String(customers[0]),configuration:"bpc_1UQduW2MI0v3aLysMQBGbq6f",return_url:origin+"/"});
 const response=await fetch("https://api.stripe.com/v1/billing_portal/sessions",{method:"POST",headers:{Authorization:"Bearer "+secret,"Content-Type":"application/x-www-form-urlencoded"},body:params});
 const data=await response.json().catch(()=>({}));
 if(!response.ok||!data.url?.startsWith("https://billing.stripe.com/"))return reply(502,{error:"Billing portal unavailable"});
 return reply(200,{url:data.url});
});